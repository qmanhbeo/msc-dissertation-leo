"""
SDG 17 sparse-reference sensitivity diagnostic.

This appendix-stage diagnostic probes how sensitive the SDG 17 headline result is to the
fact that its reference centroid is built from only 31 expert-labelled benchmark texts,
rather than from the larger OSDG reference corpus used for SDGs 1--16.

Method:
  1. Bootstrap the 31 SDG 17 benchmark texts with replacement.
  2. Rebuild only the SDG 17 centroid for each resample.
  3. Re-score only the SDG 17 column against fixed scores for the other 16 SDGs.
  4. Reconstruct the SDG 17 research and policy clusters induced by that resampled centroid.
  5. Recompute the resulting SDG 17 within-goal semantic gap.

This is a conditional reference-set sensitivity check, not a formal inferential confidence
interval over substantive SDG 17 reality.

Run from project root:
    python code/3_main_analysis/3_appendix/6_sdg17_reference_sensitivity.py
"""

